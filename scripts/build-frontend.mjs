import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { loadGroups } from "./group-config.mjs";

const source = resolve("frontend");
const output = resolve("dist");

function groupConfigSource(group) {
  return `// Generated by scripts/build-frontend.mjs. Do not edit this copy.\nexport const GROUP_CONFIG = Object.freeze(${JSON.stringify({
    id: group.id,
    name: group.name,
    apiUrl: group.apiUrl,
    useDemoData: group.useDemoData,
    migrateLegacyStorage: group.migrateLegacyStorage
  }, null, 2)});\n`;
}

function escapeHtml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function replaceRequired(sourceText, expected, replacement, path) {
  if (!sourceText.includes(expected)) {
    throw new Error(`${path} is missing the expected template text: ${expected}`);
  }
  return sourceText.replace(expected, replacement);
}

async function customizeGroup(target, group) {
  await writeFile(join(target, "group-config.js"), groupConfigSource(group));

  const title = `EvenUp – ${group.name}`;
  const indexPath = join(target, "index.html");
  const index = await readFile(indexPath, "utf8");
  await writeFile(indexPath, replaceRequired(
    index,
    "<title>EvenUp</title>",
    `<title>${escapeHtml(title)}</title>`,
    indexPath
  ));

  const manifestPath = join(target, "manifest.webmanifest");
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  manifest.name = title;
  manifest.short_name = group.name;
  manifest.start_url = "./#/record";
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}

function redirectHtml(defaultPath) {
  const target = `./${defaultPath}/`;
  return `<!doctype html>
<html lang="ja">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta http-equiv="refresh" content="0; url=${target}" />
    <title>EvenUp</title>
  </head>
  <body>
    <p><a href="${target}">EvenUpを開く</a></p>
  </body>
</html>\n`;
}

const allGroups = await loadGroups();
const groups = allGroups.filter((group) => group.enabled);
const defaultGroup = groups.find((group) => group.default);
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });

for (const group of groups) {
  const target = join(output, group.path);
  await mkdir(dirname(target), { recursive: true });
  await cp(source, target, { recursive: true });
  await customizeGroup(target, group);
  console.log(`Built ${group.id}: dist/${group.path}/`);
}

const redirect = redirectHtml(defaultGroup.path);
await writeFile(join(output, "index.html"), redirect);
await writeFile(join(output, "404.html"), redirect);
